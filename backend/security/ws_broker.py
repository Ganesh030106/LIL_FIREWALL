"""Horizontal WebSocket Broadcast Broker for Volcano AI Firewall."""

from __future__ import annotations

import abc
import json
import logging
import os
import threading
import uuid
from typing import Any, Callable, List, Optional

logger = logging.getLogger("volcano.ws_broker")

BroadcastCallback = Callable[[str, Any, str], None]


class BaseWsBroker(abc.ABC):
    """Abstract base class for WebSocket horizontal broadcast brokers."""

    def __init__(self, origin_id: Optional[str] = None) -> None:
        self.origin_id = origin_id or uuid.uuid4().hex[:12]
        self._callbacks: List[BroadcastCallback] = []
        self._lock = threading.Lock()

    def subscribe(self, callback: BroadcastCallback) -> None:
        """Register a local listener callback (event_type, data, timestamp)."""
        with self._lock:
            if callback not in self._callbacks:
                self._callbacks.append(callback)

    def unsubscribe(self, callback: BroadcastCallback) -> None:
        with self._lock:
            if callback in self._callbacks:
                self._callbacks.remove(callback)

    @abc.abstractmethod
    def publish(self, event_type: str, data: Any, timestamp: Optional[str] = None) -> None:
        """Publish broadcast across all replicas and local listeners."""
        raise NotImplementedError

    @abc.abstractmethod
    def close(self) -> None:
        """Clean up broker connections."""
        raise NotImplementedError


class InProcessWsBroker(BaseWsBroker):
    """
    Default in-process WebSocket broker.
    Directly dispatches broadcasts to in-memory local subscribers.
    """

    def publish(self, event_type: str, data: Any, timestamp: Optional[str] = None) -> None:
        ts = timestamp or ""
        with self._lock:
            cbs = list(self._callbacks)
        for cb in cbs:
            try:
                cb(event_type, data, ts)
            except Exception as exc:
                logger.error("Error invoking WebSocket local callback: %s", exc)

    def close(self) -> None:
        pass


class RedisPubSubBroker(BaseWsBroker):
    """
    Distributed Redis Pub/Sub WebSocket broker.
    Publishes every broadcast to a shared Redis channel.
    Replicas listen to the channel and relay incoming messages to their local sockets.
    Origin ID filter guarantees that a replica does not re-broadcast its own messages.
    """

    def __init__(
        self,
        redis_client: Any,
        channel: str = "volcano:ws:broadcast",
        origin_id: Optional[str] = None,
    ) -> None:
        super().__init__(origin_id=origin_id)
        self.redis = redis_client
        self.channel = channel
        self._running = True
        self._pubsub: Optional[Any] = None

        self._start_subscriber()

    def _start_subscriber(self) -> None:
        try:
            self._pubsub = self.redis.pubsub()
            self._pubsub.subscribe(self.channel)
            self._listener_thread = threading.Thread(target=self._listen_loop, daemon=True)
            self._listener_thread.start()
        except Exception as exc:
            logger.error("Failed to start Redis Pub/Sub subscriber on %s: %s", self.channel, exc)

    def _listen_loop(self) -> None:
        while self._running:
            try:
                if not self._pubsub:
                    break
                message = self._pubsub.get_message(ignore_subscribe_messages=True, timeout=0.5)
                if not message:
                    continue

                raw_data = message.get("data")
                if not raw_data:
                    continue

                if isinstance(raw_data, bytes):
                    raw_data = raw_data.decode("utf-8")

                try:
                    payload = json.loads(raw_data)
                except Exception:
                    continue

                msg_origin_id = payload.get("origin_id")
                # Origin ID filter: do NOT re-broadcast messages generated by this replica
                if msg_origin_id == self.origin_id:
                    continue

                event_type = payload.get("type", "broadcast")
                data = payload.get("data")
                timestamp = payload.get("timestamp", "")

                with self._lock:
                    cbs = list(self._callbacks)

                for cb in cbs:
                    try:
                        cb(event_type, data, timestamp)
                    except Exception as exc:
                        logger.error("Error in RedisPubSubBroker subscriber relay: %s", exc)
            except Exception as exc:
                if self._running:
                    logger.debug("Redis PubSub listener iteration error: %s", exc)
                    import time
                    time.sleep(0.2)

    def publish(self, event_type: str, data: Any, timestamp: Optional[str] = None) -> None:
        ts = timestamp or ""
        envelope = {
            "origin_id": self.origin_id,
            "type": event_type,
            "data": data,
            "timestamp": ts,
        }
        raw_json = json.dumps(envelope)

        # 1. Publish to Redis channel for peer replicas
        try:
            self.redis.publish(self.channel, raw_json)
        except Exception as exc:
            logger.error("Failed publishing to Redis Pub/Sub channel %s: %s", self.channel, exc)

        # 2. Directly deliver to local subscribers on the publishing replica
        with self._lock:
            cbs = list(self._callbacks)
        for cb in cbs:
            try:
                cb(event_type, data, ts)
            except Exception as exc:
                logger.error("Error invoking local callback on publisher: %s", exc)

    def close(self) -> None:
        self._running = False
        if self._pubsub:
            try:
                self._pubsub.unsubscribe()
                self._pubsub.close()
            except Exception:
                pass
            finally:
                self._pubsub = None


def get_ws_broker(
    backend: Optional[str] = None,
    redis_url: Optional[str] = None,
    channel: Optional[str] = None,
    redis_client: Optional[Any] = None,
) -> BaseWsBroker:
    """Factory creating the appropriate WebSocket broadcast broker."""
    chosen_backend = (backend or os.getenv("VOLCANO_WS_BROKER", "memory")).lower().strip()
    if chosen_backend == "redis":
        ch = channel or os.getenv("VOLCANO_WS_CHANNEL", "volcano:ws:broadcast")
        client = redis_client
        if client is None:
            try:
                import redis
                url = redis_url or os.getenv("VOLCANO_REDIS_URL", "redis://localhost:6379/0")
                client = redis.from_url(url, decode_responses=True)
            except Exception as exc:
                logger.error("Failed to connect to Redis for WS Broker (%s). Falling back to in-process broker.", exc)
                return InProcessWsBroker()
        return RedisPubSubBroker(redis_client=client, channel=ch)
    return InProcessWsBroker()
